/** Años del más nuevo al más antiguo (incluye el próximo año: los modelos se venden con año adelantado). */
export function aniosVehiculo(desde = 1980): string[] {
  const hasta = new Date().getFullYear() + 1;
  return Array.from({ length: hasta - desde + 1 }, (_, i) => String(hasta - i));
}

/** Patente con guion entre letras y números: ABCD12 → ABCD-12, AB1234 → AB-1234. */
export function formatoPatente(v: string): string {
  const limpio = v.toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 6);
  const m = /^([A-Z]+)(\d+)$/.exec(limpio);
  return m ? `${m[1]}-${m[2]}` : limpio;
}
